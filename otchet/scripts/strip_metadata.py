#!/usr/bin/env python
"""Remove generator and author fingerprints from delivered files.

A delivered report should not advertise how it was produced. python-docx leaves
``creator: python-docx`` plus ``description: generated by python-docx``, python-pptx
leaves ``lastModifiedBy: Steve Canny``, openpyxl leaves ``creator: openpyxl``,
ReportLab leaves ``Producer: ReportLab PDF Library``, ffmpeg leaves
``encoder=Lavf62.13.101``. This script rewrites those blocks to a neutral state:

* OOXML (.docx/.xlsx/.pptx/...): rebuild ``docProps/core.xml`` (only title, optional
  author, real created/modified), blank the producer fields in ``docProps/app.xml``,
  drop ``docProps/custom.xml`` and the packaged thumbnail.
* PDF: keep only /CreationDate and /ModDate, drop Producer / Creator / Author /
  Title / Subject / Keywords and the XMP stream.
* Raster images: re-encode without EXIF, XMP or text chunks (ICC profile is kept).
* Video: remux with ``-map_metadata -1`` and bitexact flags so no ``encoder=Lavf`` tag.

Usage::

    python strip_metadata.py FILE [FILE ...]             # clean in place
    python strip_metadata.py --check FILE [FILE ...]     # report only, exit 1 if dirty
    python strip_metadata.py --author "Ivan Ivanov" --title "Otchet" report.docx

Exit codes: 0 clean or cleaned, 1 still dirty (``--check``) or failed, 2 bad usage.
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

OOXML = {".docx", ".docm", ".dotx", ".dotm", ".xlsx", ".xlsm", ".xltx", ".xltm",
         ".pptx", ".pptm", ".potx", ".potm", ".ppsx"}
RASTER = {".png", ".jpg", ".jpeg", ".tif", ".tiff", ".webp", ".bmp"}
VIDEO = {".mp4", ".mov", ".m4v", ".mkv"}

# Substrings that betray a generator or an AI tool. Matched case-insensitively.
FINGERPRINTS = (
    "python-docx", "python-pptx", "openpyxl", "xlsxwriter", "reportlab", "pypdf",
    "fpdf", "docx4j", "aspose", "generated by", "generated using", "created by",
    "steve canny", "lavf", "lavc", "libx264", "ffmpeg", "matplotlib", "pandas",
    "manim", "cline", "copilot", "chatgpt", "openai", "anthropic", "claude", "gpt-",
    "llm", "ai-generated", "generated with ai",
)

CORE_TMPL = (
    '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
    '<cp:coreProperties'
    ' xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties"'
    ' xmlns:dc="http://purl.org/dc/elements/1.1/"'
    ' xmlns:dcterms="http://purl.org/dc/terms/"'
    ' xmlns:dcmitype="http://purl.org/dc/dcmitype/"'
    ' xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">'
    "{body}</cp:coreProperties>"
)

# Fields in docProps/app.xml that name the tool that produced the file.
APP_FIELDS = ("Application", "AppVersion", "Manager", "Company", "Template",
              "HyperlinkBase", "DocSecurity")


def stamps(modified: float | None = None):
    """Return (w3cdtf, pdf_date) for now or for a file mtime."""
    moment = dt.datetime.fromtimestamp(modified, dt.timezone.utc) if modified else (
        dt.datetime.now(dt.timezone.utc))
    return (moment.strftime("%Y-%m-%dT%H:%M:%SZ"),
            moment.strftime("D:%Y%m%d%H%M%SZ"))


def looks_like_fingerprint(value: str) -> bool:
    low = value.lower()
    return any(mark in low for mark in FINGERPRINTS)


def xml_escape(text: str) -> str:
    return (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


# --------------------------------------------------------------------------- OOXML

def read_zip(path: Path):
    with zipfile.ZipFile(path) as zf:
        return {info.filename: zf.read(info.filename) for info in zf.infolist()}


def write_zip(path: Path, parts: dict[str, bytes]) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zf:
        for name, data in parts.items():
            zf.writestr(name, data)
    os.replace(tmp, path)


def ooxml_findings(parts: dict[str, bytes]) -> list[str]:
    found = []
    core = parts.get("docProps/core.xml", b"").decode("utf-8", "replace")
    for tag in ("dc:creator", "dc:description", "cp:lastModifiedBy", "dc:subject",
                "dc:title", "cp:keywords", "cp:category"):
        for match in re.findall(rf"<{tag}[^>]*>(.*?)</{tag}>", core, re.S):
            if match.strip() and looks_like_fingerprint(match):
                found.append(f"{tag}={match.strip()}")
    # an empty core is fine, but the fake 2013 template dates are still a tell
    for tag in ("dcterms:created", "dcterms:modified"):
        for match in re.findall(rf"<{tag}[^>]*>(.*?)</{tag}>", core, re.S):
            if match.strip()[:4] in ("2011", "2012", "2013"):
                found.append(f"{tag}={match.strip()}")
    app = parts.get("docProps/app.xml", b"").decode("utf-8", "replace")
    for field in APP_FIELDS:
        for match in re.findall(rf"<{field}>(.*?)</{field}>", app, re.S):
            if match.strip() and (field in ("Application", "AppVersion")
                                  or looks_like_fingerprint(match)):
                found.append(f"{field}={match.strip()}")
    for name in parts:
        if name.startswith("docProps/thumbnail."):
            found.append(f"part={name}")
    if "docProps/custom.xml" in parts:
        found.append("part=docProps/custom.xml")
    return found


def clean_ooxml(path: Path, author: str | None, title: str | None) -> None:
    parts = read_zip(path)
    w3c, _ = stamps(path.stat().st_mtime)

    body = []
    if title:
        body.append(f"<dc:title>{xml_escape(title)}</dc:title>")
    if author:
        body.append(f"<dc:creator>{xml_escape(author)}</dc:creator>")
        body.append(f"<cp:lastModifiedBy>{xml_escape(author)}</cp:lastModifiedBy>")
    body.append(f'<dcterms:created xsi:type="dcterms:W3CDTF">{w3c}</dcterms:created>')
    body.append(f'<dcterms:modified xsi:type="dcterms:W3CDTF">{w3c}</dcterms:modified>')
    parts["docProps/core.xml"] = CORE_TMPL.format(body="".join(body)).encode("utf-8")

    if "docProps/app.xml" in parts:
        app = parts["docProps/app.xml"].decode("utf-8", "replace")
        for field in APP_FIELDS:
            app = re.sub(rf"(<{field}>)(.*?)(</{field}>)", r"\1\3", app, flags=re.S)
        parts["docProps/app.xml"] = app.encode("utf-8")

    # packaged previews and custom property bags can both name the tool
    for name in list(parts):
        if name.startswith("docProps/thumbnail.") or name == "docProps/custom.xml":
            del parts[name]
    if "[Content_Types].xml" in parts:
        ct = parts["[Content_Types].xml"].decode("utf-8", "replace")
        ct = re.sub(r'<Override[^>]*PartName="/docProps/(custom\.xml|thumbnail\.[a-z]+)"[^>]*/>',
                    "", ct)
        parts["[Content_Types].xml"] = ct.encode("utf-8")
    if "_rels/.rels" in parts:
        rels = parts["_rels/.rels"].decode("utf-8", "replace")
        rels = re.sub(r'<Relationship[^>]*Target="docProps/(custom\.xml|thumbnail\.[a-z]+)"[^>]*/>',
                      "", rels)
        parts["_rels/.rels"] = rels.encode("utf-8")

    write_zip(path, parts)


# ----------------------------------------------------------------------------- PDF

def clean_pdf(path: Path, author: str | None, title: str | None) -> None:
    import pypdf

    writer = pypdf.PdfWriter(clone_from=str(path))

    info = writer._info
    if info is not None:
        keep = {"/CreationDate", "/ModDate"}
        for key in list(info.keys()):
            if key in keep and not looks_like_fingerprint(str(info[key])):
                continue
            del info[key]
        if author:
            info["/Author"] = author
        if title:
            info["/Title"] = title

    root = writer._root_object
    if "/Metadata" in root:
        del root["/Metadata"]

    tmp = path.with_suffix(path.suffix + ".tmp")
    with open(tmp, "wb") as fh:
        writer.write(fh)
    os.replace(tmp, path)


def pdf_findings(path: Path) -> list[str]:
    import pypdf

    reader = pypdf.PdfReader(str(path))
    found = []
    for key, value in dict(reader.metadata or {}).items():
        text = str(value)
        if looks_like_fingerprint(text):
            found.append(f"{key}={text}")
    try:
        if "/Metadata" in reader.trailer["/Root"]:
            found.append("XMP=/Metadata present")
    except Exception:
        pass
    return found


# -------------------------------------------------------------------------- RASTER

def clean_image(path: Path) -> None:
    from PIL import Image

    with Image.open(path) as img:
        params = {}
        if img.info.get("icc_profile"):
            params["icc_profile"] = img.info["icc_profile"]
        if img.mode == "P":
            img = img.convert("RGBA" if "transparency" in img.info else "RGB")
        tmp = path.with_name(path.stem + ".clean" + path.suffix)
        img.save(tmp, **params)
    os.replace(tmp, path)


def image_findings(path: Path) -> list[str]:
    from PIL import Image

    with Image.open(path) as img:
        found = []
        if img.getexif():
            found.append(f"EXIF={sorted(str(k) for k in img.getexif())}")
        for key in ("Software", "Author", "Artist", "Comment", "Description",
                    "Copyright", "XML:com.adobe.xmp", "xmp"):
            if img.info.get(key):
                found.append(f"{key}={str(img.info[key])[:60]}")
        return found


# --------------------------------------------------------------------------- VIDEO

def clean_video(path: Path) -> None:
    if not shutil.which("ffmpeg"):
        raise RuntimeError("ffmpeg is not on PATH")
    tmp = path.with_name(path.stem + ".clean" + path.suffix)
    args = ["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(path),
            "-map_metadata", "-1", "-map", "0", "-c", "copy",
            "-fflags", "+bitexact", "-flags:v", "+bitexact", "-flags:a", "+bitexact",
            str(tmp)]
    subprocess.run(args, check=True)
    os.replace(tmp, path)


def video_findings(path: Path) -> list[str]:
    if not shutil.which("ffprobe"):
        return []
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                          "format_tags:stream_tags", "-of", "default=nw=1", str(path)],
                         capture_output=True, text=True)
    return [line.strip() for line in out.stdout.splitlines()
            if line.startswith("TAG:") and looks_like_fingerprint(line)]


# ------------------------------------------------------------------------- driver

def inspect(path: Path) -> list[str]:
    suffix = path.suffix.lower()
    if suffix in OOXML:
        return ooxml_findings(read_zip(path))
    if suffix == ".pdf":
        return pdf_findings(path)
    if suffix in RASTER:
        return image_findings(path)
    if suffix in VIDEO:
        return video_findings(path)
    return []


def clean(path: Path, author: str | None, title: str | None) -> None:
    suffix = path.suffix.lower()
    if suffix in OOXML:
        clean_ooxml(path, author, title)
    elif suffix == ".pdf":
        clean_pdf(path, author, title)
    elif suffix in RASTER:
        clean_image(path)
    elif suffix in VIDEO:
        clean_video(path)
    else:
        raise ValueError(f"unsupported format: {suffix or path.name}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Strip generator/AI fingerprints from delivered files.")
    parser.add_argument("files", nargs="+", type=Path)
    parser.add_argument("--check", action="store_true",
                        help="only report what would be removed (exit 1 if dirty)")
    parser.add_argument("--author", default=None,
                        help="real author to record instead of nothing")
    parser.add_argument("--title", default=None,
                        help="document title to record instead of nothing")
    args = parser.parse_args(argv)

    dirty = 0
    failed = 0
    for path in args.files:
        if not path.is_file():
            print(f"missing  {path}")
            failed += 1
            continue
        try:
            findings = inspect(path)
            if args.check:
                if findings:
                    dirty += 1
                    print(f"dirty    {path}  " + "; ".join(findings))
                else:
                    print(f"clean    {path}")
                continue

            if not findings and not (args.author or args.title):
                print(f"clean    {path}  (nothing to strip)")
                continue
            clean(path, args.author, args.title)
            left = inspect(path)
            if left:
                failed += 1
                print(f"partial  {path}  still: " + "; ".join(left))
            else:
                detail = "; ".join(findings) if findings else "metadata rewritten"
                print(f"cleaned  {path}  removed: {detail}")
        except Exception as exc:                       # noqa: BLE001 - report and continue
            failed += 1
            print(f"error    {path}  {type(exc).__name__}: {exc}")

    if failed:
        return 1
    if args.check and dirty:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
